def _run_task_benchmark(
    task_title: str,
    prompt: str,
    cohort: List[str],
    tests: List[Dict[str, str]],
    mode: str,
) -> Dict[str, Any]:
    backend = LocalHybridEmbedder()
    scorer = UniquenessScorer(backend=backend, config=ScoringConfig(mode=mode))

    # 全テスト群を共通2D PCA平面に射影するため一括埋め込み
    all_docs = cohort + [t["text"] for t in tests]
    all_vecs = backend.embed(all_docs)
    c_vecs = all_vecs[: len(cohort)]
    t_vecs = all_vecs[len(cohort) :]
    mu = np.mean(c_vecs, axis=0)
    centered_all = all_vecs - mu
    _, s, vt = np.linalg.svd(centered_all, full_matrices=False)
    coords = centered_all @ vt[:2].T
    explained = (s[:2] ** 2) / max(float(np.sum(s**2)), 1e-12)

    pca_cohort_points = [
        {"id": f"AI-{i+1}", "x": round(float(coords[i, 0]), 4), "y": round(float(coords[i, 1]), 4)}
        for i in range(len(cohort))
    ]

    items: List[Dict[str, Any]] = []
    print(f"\n==================== {task_title} ====================")
    print(
        f"{'テスト群':34s} | {'総合':>5s} | {'純独自':>5s} | {'適合G':>5s} | "
        f"{'ΔVS':>6s} | {'MahaZ':>6s} | {'主張被':>5s} | 判定"
    )
    print("-" * 106)
    for idx, t in enumerate(tests):
        res = scorer.score(
            assignment_prompt=prompt,
            draft=t["text"],
            reference_cohort=cohort,
        )
        pt = {
            "x": round(float(coords[len(cohort) + idx, 0]), 4),
            "y": round(float(coords[len(cohort) + idx, 1]), 4),
        }
        items.append({**t, "result": res, "pca_point": pt})
        print(
            f"{t['name']:34s} | {res.final_score:5.1f} | {res.raw_originality:5.1f} | "
            f"{res.relevance_gate:5.2f} | +{res.raw_stats['delta_vendi_score']:5.3f} | "
            f"{res.raw_stats['mahalanobis_z_score']:+5.2f} | "
            f"{res.raw_stats['mean_claim_overlap_rate']*100:4.0f}% | {res.grade}"
        )

    # 分離アサーション検証
    by_key = {it["group_key"]: it["result"] for it in items}
    margin_d_vs_a = by_key["D"].final_score - by_key["A"].final_score
    margin_d_vs_b = by_key["D"].final_score - by_key["B"].final_score
    margin_d_vs_c = by_key["D"].final_score - by_key["C"].final_score
    passed = (
        margin_d_vs_a >= 25.0
        and margin_d_vs_b >= 20.0
        and margin_d_vs_c >= 30.0
        and by_key["C"].relevance_gate < 0.45
    )
    print(
        f"\n[分離検証] D-A: +{margin_d_vs_a:.1f}pt | D-B(言い換え撃破): +{margin_d_vs_b:.1f}pt | "
        f"D-C(論点ズレ遮断): +{margin_d_vs_c:.1f}pt | CのゲートG={by_key['C'].relevance_gate:.2f} -> "
        f"{'PASS' if passed else 'CHECK'}"
    )
    return {
        "task_title": task_title,
        "prompt": prompt,
        "items": items,
        "pca_cohort_points": pca_cohort_points,
        "pca_explained": [float(v) for v in explained],
        "passed": passed,
    }


def _test_mcp_protocol() -> bool:
    """MCPサーバーのJSON-RPC 2.0プロトコル（initialize / tools/list / tools/call）を疎通検証."""
    r_init = handle_jsonrpc_message({"jsonrpc": "2.0", "id": 1, "method": "initialize"})
    r_list = handle_jsonrpc_message({"jsonrpc": "2.0", "id": 2, "method": "tools/list"})
    r_call = handle_jsonrpc_message(
        {
            "jsonrpc": "2.0",
            "id": 3,
            "method": "tools/call",
            "params": {
                "name": "compare_draft_revisions",
                "arguments": {
                    "assignment_prompt": TASK1_PROMPT,
                    "before_draft": TASK1_TESTS[1]["text"],  # Group B (言い換え)
                    "after_draft": TASK1_TESTS[3]["text"],  # Group D (独自)
                    "reference_cohort": TASK1_COHORT,
                    "mode": "report",
                    "provider": "local",
                },
            },
        }
    )
    assert r_init and "protocolVersion" in r_init["result"]
    assert r_list and len(r_list["result"]["tools"]) >= 4
    assert r_call and not r_call["result"]["isError"]
    cmp_payload = json.loads(r_call["result"]["content"][0]["text"])
    print("\n==================== MCP 疎通検証 (compare_draft_revisions) ====================")
    print(
        f"Before (Group B): {cmp_payload['before']['final_score']}点 -> "
        f"After (Group D): {cmp_payload['after']['final_score']}点 "
        f"(+{cmp_payload['delta']['score_change']}pt, ΔVS {cmp_payload['delta']['vendi_change']:+.4f}, "
        f"主張被り {cmp_payload['delta']['claim_overlap_change_pct']:+.1f}%)"
    )
    return cmp_payload["delta"]["score_change"] > 20.0


